def money(n):
    return f"{n:,}".replace(",", NB)


def esc(s):
    return html.escape(s, quote=True)


def price_html(p):
    if isinstance(p, tuple):
        old, new = p
        return f'<span class="price price--deal"><s>{money(old)}</s> {money(new)}</span>'
    if isinstance(p, str):
        return f'<span class="price">{esc(p).replace(" ", NB).replace(NB + "/" + NB, " / ")}</span>'
    return f'<span class="price">{money(p)}</span>'


def item_html(it):
    name, price, *rest = it
    note = rest[0] if rest else ""
    tag = ""
    if note in ("Новинка", "Акция"):
        tag = f' <em class="tag">{note.lower()}</em>'
        note = ""
    elif note.startswith("Акция. "):
        tag = ' <em class="tag">акция</em>'
        note = note[len("Акция. "):]
    p = f"<p>{esc(note)}</p>" if note else ""
    return f"<li><div><h4>{esc(name)}{tag}</h4>{p}</div>{price_html(price)}</li>"


def build():
    tabs, panels = [], []
    for i, (key, title, img, groups) in enumerate(MENU):
        on = i == 0
        tabs.append(
            f'<button role="tab" aria-selected="{str(on).lower()}" aria-controls="m-{key}" id="t-{key}"'
            + ("" if on else ' tabindex="-1"') + f">{esc(title)}</button>"
        )
        body = []
        if len(groups) > 2:
            chips = "".join(
                f'<a href="#g-{key}-{j}">{esc(g[0])}</a>' for j, g in enumerate(groups)
            )
            body.append(f'<nav class="subnav" aria-label="{esc(title)}: разделы">{chips}</nav>')
        for j, (gname, vol, items) in enumerate(groups):
            v = f' <span class="mgroup__vol">{esc(vol)}</span>' if vol else ""
            lis = "\n              ".join(item_html(it) for it in items)
            head = "" if len(groups) == 1 and gname == title else f'<h3 class="mgroup__h">{esc(gname)}{v}</h3>'
            body.append(
                f'<section class="mgroup" id="g-{key}-{j}">{head}\n            <ul class="dishes">\n              {lis}\n            </ul>\n          </section>'
            )
        hidden = "" if on else " hidden"
        panels.append(
            f'<div class="panel" role="tabpanel" id="m-{key}" aria-labelledby="t-{key}" data-img="{img}"{hidden}>\n          '
            + "\n          ".join(body)
            + "\n        </div>"
        )
    first_img = MENU[0][2]
    return f"""<!-- MENU:START (собирается из tools/build_menu.py) -->
    <div class="tabs" role="tablist" aria-label="Разделы меню">
      {chr(10).join('      ' + t if k else t for k, t in enumerate(tabs))}
    </div>

    <div class="menu__grid">
      <figure class="menu__photo" aria-hidden="true">
        <img src="{first_img}" alt="" id="menu-img" loading="lazy">
      </figure>
      <div class="menu__panels">
        {chr(10).join('        ' + p if k else p for k, p in enumerate(panels))}
        <p class="menu__more">Обслуживание 10%. Цены могут меняться, актуальное меню у официанта. Вопрос по блюду? <a href="https://ig.me/m/millennium_barr" target="_blank" rel="noopener">Напишите в Direct</a></p>
      </div>
    </div>
    <!-- MENU:END -->"""


def main():
    root = Path(__file__).resolve().parent.parent
    page = root / "index.html"
    s = page.read_text(encoding="utf-8")
    pat = re.compile(r"<!-- MENU:START.*?<!-- MENU:END -->", re.S)
    if not pat.search(s):
        raise SystemExit("В index.html нет меток MENU:START / MENU:END")
    s = pat.sub(lambda m: build(), s, count=1)
    page.write_text(s, encoding="utf-8")
    n = sum(len(g[2]) for _, _, _, gs in MENU for g in gs)
    print(f"Меню собрано: {n} позиций")


if __name__ == "__main__":
    main()
